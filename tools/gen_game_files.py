"""Writes the launcher's list of the game's data files and their sizes (launcher/windows/
game_files_<title>.inc) from a working, merged game folder (base game + 1.21 update):

    python tools/gen_game_files.py <CUSA14876-1.21 folder> launcher/windows/game_files_cusa14876.inc

Only names and sizes of archives\\ and sce_module\\ go in it, nothing of the game itself. The
launcher checks a prepared folder against it, so a dump that a broken extraction left with empty
or missing files is reported before the game crashes on it (exit code 3)."""
import os
import sys


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    game, out = sys.argv[1], sys.argv[2]
    rows = []
    for sub in ('archives', 'sce_module'):
        for root, _, files in os.walk(os.path.join(game, sub)):
            for f in files:
                p = os.path.join(root, f)
                rows.append((os.path.relpath(p, game).replace('\\', '/'), os.path.getsize(p)))
    rows.sort()
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/gen_game_files.py from a working merged folder: the game\'s data\n')
        f.write(f'// files (archives/, sce_module/) and their sizes. {len(rows)} files.\n')
        for rel, size in rows:
            f.write(f'    {{"{rel}", {size}ull}},\n')
    print(f'{out}: {len(rows)} files')


if __name__ == '__main__':
    main()
